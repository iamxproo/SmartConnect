export function tailwindThemeCss(): string {
  const sizes = Object.keys(typography.fontSize).flatMap((name) => [
    decl(`--text-${name}`, `var(--sc-font-size-${name})`),
    decl(
      `--text-${name}--line-height`,
      `var(--sc-line-height-${name === '2xl' || name === '3xl' ? 'tight' : 'normal'})`,
    ),
  ]);
  return [
    HEADER,
    '',
    '@theme inline {',
    "  /* Tokens only: remove Tailwind's default palette so raw colours (bg-red-500, #hex) cannot creep in. */",
    decl('--color-*', 'initial'),
    ...tailwindColors.map(([utility, token]) => decl(`--color-${utility}`, `var(--sc-color-${token})`)),
    '',
    decl('--font-sans', 'var(--sc-font-sans)'),
    decl('--font-mono', 'var(--sc-font-mono)'),
    ...sizes,
    '',
    ...Object.keys(radius).map((name) => decl(`--radius-${name}`, `var(--sc-radius-${name})`)),
    ...Object.keys(shadows.light).map((name) => decl(`--shadow-${name}`, `var(--sc-shadow-${name})`)),
    ...Object.keys(motion.easing).map((name) => decl(`--ease-${name}`, `var(--sc-ease-${name})`)),
    '}',
    '',
  ].join('\n');
}

/** Colour pairs used for foreground-on-background, checked against WCAG thresholds in tests. */
export const tailwindColorMap: ReadonlyArray<readonly [string, string]> = tailwindColors;
