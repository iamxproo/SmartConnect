#!/usr/bin/env node
// SmartConnect database tooling (local development). See docs/database/migrations.md.
//
//   node infrastructure/scripts/db.mjs bootstrap [--rotate=<svc>|all] [--role=app|migrator]
//   node infrastructure/scripts/db.mjs migrate   [--service=<svc>]
//   node infrastructure/scripts/db.mjs status    [--service=<svc>]
//   node infrastructure/scripts/db.mjs new-migration --service=<svc> --name=<snake_case> [--empty]
//   node infrastructure/scripts/db.mjs check-drift [--service=<svc>]
//   node infrastructure/scripts/db.mjs rehearse
//
// bootstrap/migrate/status act on the DEV database. new-migration/check-drift/rehearse only ever use
// the disposable TEST instance (shadow databases / full migration rehearsal); they never touch DEV.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import {
  SERVICES,
  applyBootstrap,
  assertService,
  connectionUrl,
  generatePassword,
  isContainerRunning,
  loadTargets,
  parseEnvFile,
  provisionTestInstance,
  roleNames,
  runPrisma,
  runSql,
  serviceDir,
  setRolePasswords,
  stageSecretFile,
} from './lib/db-lib.mjs';

process.env.PRISMA_HIDE_UPDATE_MESSAGE = '1';

const [command, ...rest] = process.argv.slice(2);
const opts = Object.fromEntries(
  rest.map((a) => {
    const m = a.match(/^--([a-z-]+)(?:=(.*))?$/);
    if (!m) fail(`unrecognised argument: ${a}`);
    return [m[1], m[2] ?? true];
  }),
);

function fail(message) {
  console.error(`✖ ${message}`);
  process.exit(1);
}

function selectedServices() {
  if (!opts.service) return SERVICES;
  assertService(opts.service);
  return [opts.service];
}

function requireRunning(target) {
  if (!isContainerRunning(target.container)) {
    const profile = target.name === 'test' ? ' --profile test' : '';
    fail(
      `${target.container} is not running. Start it with:\n  docker compose -f infrastructure/compose/docker-compose.yml --env-file .env${profile} up -d`,
    );
  }
}

const hasMigrations = (svc) => {
  const dir = path.join(serviceDir(svc), 'prisma/migrations');
  return existsSync(dir) && readdirSync(dir).some((d) => /^\d{14}_/.test(d));
};

function passwordFromUrl(url, expectedUser) {
  if (!url) return undefined;
  const parsed = new URL(url);
  if (decodeURIComponent(parsed.username) !== expectedUser) {
    fail(`credential file names user "${parsed.username}" but "${expectedUser}" was expected — refusing to continue`);
  }
  return decodeURIComponent(parsed.password) || undefined;
}

function migrationEnv(svc) {
  const url = parseEnvFile(path.join(serviceDir(svc), '.env.migration')).MIGRATION_DATABASE_URL;
  if (!url) fail(`${svc}: no .env.migration — run \`make db-bootstrap\` first`);
  passwordFromUrl(url, roleNames(svc).migrator); // asserts the CLI will run as the migrator role
  return { MIGRATION_DATABASE_URL: url };
}

// ---------------------------------------------------------------------------------------------
const commands = {
  bootstrap() {
    const dev = loadTargets().dev;
    requireRunning(dev);
    applyBootstrap(dev);
    console.log('✔ schemas, roles and privileges applied');

    const rotate = opts.rotate === 'all' ? SERVICES : opts.rotate ? [opts.rotate] : [];
    rotate.forEach(assertService);
    const rotateRoles = opts.role ? [opts.role] : ['app', 'migrator'];

    const credentials = {};
    const files = [];
    for (const svc of SERVICES) {
      const dir = serviceDir(svc);
      mkdirSync(dir, { recursive: true });
      const roles = roleNames(svc);
      const runtimeFile = path.join(dir, '.env');
      const migrationFile = path.join(dir, '.env.migration');
      const fresh = (kind) => rotate.includes(svc) && rotateRoles.includes(kind);
      const appPassword =
        (!fresh('app') && passwordFromUrl(parseEnvFile(runtimeFile).DATABASE_URL, roles.app)) || generatePassword();
      const migratorPassword =
        (!fresh('migrator') && passwordFromUrl(parseEnvFile(migrationFile).MIGRATION_DATABASE_URL, roles.migrator)) ||
        generatePassword();
      credentials[roles.app] = appPassword;
      credentials[roles.migrator] = migratorPassword;

      const common = { host: dev.host, port: dev.port, database: dev.database, schema: svc };
      files.push([
        runtimeFile,
        [
          '# Generated by `make db-bootstrap` (infrastructure/scripts/db.mjs). LOCAL DEVELOPMENT ONLY — never commit.',
          `# Runtime credentials: least-privilege role ${roles.app} (DML only, subject to row-level security).`,
          `DATABASE_URL=${connectionUrl({ user: roles.app, password: appPassword, ...common })}`,
          `DATABASE_SCHEMA=${svc}`,
          '',
        ].join('\n'),
      ]);
      files.push([
        migrationFile,
        [
          '# Generated by `make db-bootstrap` (infrastructure/scripts/db.mjs). LOCAL DEVELOPMENT ONLY — never commit.',
          `# Migration credentials: schema owner ${roles.migrator}. Read ONLY by the Prisma CLI via prisma.config.ts;`,
          '# the running service must never be given these.',
          `MIGRATION_DATABASE_URL=${connectionUrl({ user: roles.migrator, password: migratorPassword, ...common })}`,
          '',
        ].join('\n'),
      ]);
    }
    // Stage files first, change the database second, publish files last: a failure at any step never
    // leaves a role with a password that no credential file holds.
    const staged = files.map(([file, content]) => stageSecretFile(file, content));
    try {
      setRolePasswords(dev, credentials);
    } catch (error) {
      staged.forEach((s) => s.discard());
      throw error;
    }
    staged.forEach((s) => s.commit());
    console.log(
      `✔ credentials provisioned for ${Object.keys(credentials).length} roles (SCRAM-SHA-256 verifiers; plaintext never sent)`,
    );
    if (rotate.length)
      console.log(`↻ rotated: ${rotate.join(', ')} (${rotateRoles.join(' + ')}) — restart affected services`);

    // Prove every credential works over TCP exactly as the services will connect.
    const failures = [];
    for (const [role, password] of Object.entries(credentials)) {
      try {
        runSql(dev, 'select 1', { user: role, password });
      } catch (e) {
        failures.push(`${role}: ${e.message}`);
      }
    }
    if (failures.length) fail(`login check failed:\n  ${failures.join('\n  ')}`);
    console.log(`✔ login verified for all ${Object.keys(credentials).length} roles over TCP ${dev.host}:${dev.port}`);
  },

  migrate() {
    const dev = loadTargets().dev;
    requireRunning(dev);
    try {
      for (const svc of selectedServices()) {
        if (!hasMigrations(svc)) {
          console.log(`· ${svc}: no migrations`);
          continue;
        }
        console.log(`▶ ${svc}: prisma migrate deploy`);
        runPrisma(svc, ['migrate', 'deploy'], { env: migrationEnv(svc) });
      }
    } finally {
      // Re-assert privileges even when a later service failed: services migrated earlier in this run
      // must not keep default grants (e.g. runtime access to _prisma_migrations).
      applyBootstrap(dev);
    }
    console.log('✔ migrations applied; privileges re-asserted');
  },

  status() {
    requireRunning(loadTargets().dev);
    let pending = false;
    for (const svc of selectedServices()) {
      if (!hasMigrations(svc)) continue;
      const res = runPrisma(svc, ['migrate', 'status'], { env: migrationEnv(svc), capture: true, allowFailure: true });
      const summary = (res.stdout + res.stderr)
        .split('\n')
        .filter((l) => /up to date|not yet been applied|failed|drift|Following migration/i.test(l));
      pending ||= res.status !== 0;
      console.log(`${res.status === 0 ? '✔' : '✖'} ${svc.padEnd(15)} ${summary.join(' ') || '(see prisma output)'}`);
    }
    if (pending) process.exit(1);
  },

  'new-migration'() {
    const svc = opts.service;
    const name = opts.name;
    if (!svc || !name) fail('usage: new-migration --service=<svc> --name=<snake_case_name>');
    assertService(svc);
    if (!/^[a-z0-9_]{3,60}$/.test(name)) fail('--name must be snake_case (a-z, 0-9, _)');

    // `--from-migrations` cannot infer the provider from an empty directory without the lock file.
    const migrationsDir = path.join(serviceDir(svc), 'prisma/migrations');
    const lock = path.join(migrationsDir, 'migration_lock.toml');
    if (!existsSync(lock)) {
      mkdirSync(migrationsDir, { recursive: true });
      writeFileSync(
        lock,
        '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
      );
    }

    // --empty: a hand-written migration (policies, functions, data fixes) with no schema.prisma change.
    const sql = opts.empty
      ? '-- Hand-written migration: no schema.prisma change. Write the SQL here.\n'
      : diffAgainstShadow(svc, ['--script']).stdout;
    // A genuine no-op prints an explicit marker. Completely empty output is how Prisma 7.10's schema
    // engine fails silently (exit 0), so it must never be mistaken for "nothing to do".
    if (!sql.trim()) fail(`${svc}: prisma migrate diff produced no output — treating as a failure`);
    if (/^-- This is an empty migration\.\s*$/.test(sql.trim())) {
      console.log(
        `· ${svc}: schema.prisma matches the migrations — nothing to generate (use --empty for hand-written SQL)`,
      );
      return;
    }
    const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
    const dir = path.join(migrationsDir, `${stamp}_${name}`);
    mkdirSync(dir, { recursive: true });
    writeFileSync(path.join(dir, 'migration.sql'), wrapInTransaction(guardSchemaCreation(svc, sql)));
    console.log(`✔ wrote ${path.relative(process.cwd(), path.join(dir, 'migration.sql'))}`);
    console.log(
      '  Review it, add hand-written SQL (e.g. RLS for new tenant tables) ABOVE the final COMMIT, then `make db-migrate`.',
    );
    if (/DROP (TABLE|COLUMN|TYPE|SCHEMA)|ALTER COLUMN .* TYPE|SET NOT NULL/i.test(sql)) {
      console.log(
        '⚠ contains potentially DESTRUCTIVE or locking statements — follow docs/database/migrations.md#destructive-changes',
      );
    }
  },

  rehearse() {
    requireRunning(loadTargets().test);
    const started = Date.now();
    provisionTestInstance({ log: (m) => console.log(`▶ ${m}`) });
    console.log(
      `✔ bootstrap + all migrations applied to the TEST instance as migrator roles (${((Date.now() - started) / 1000).toFixed(1)}s)`,
    );
  },

  'check-drift'() {
    let drift = false;
    for (const svc of selectedServices()) {
      if (!hasMigrations(svc)) {
        console.log(`· ${svc.padEnd(15)} no migrations`);
        continue;
      }
      const res = diffAgainstShadow(svc, ['--exit-code']);
      const ok = res.status === 0;
      drift ||= !ok;
      console.log(
        `${ok ? '✔' : '✖'} ${svc.padEnd(15)} ${ok ? 'migrations match schema.prisma' : res.stdout.trim().split('\n').join(' ')}`,
      );
    }
    if (drift) fail('schema.prisma and migrations have drifted — run new-migration');
  },
};

/**
 * Diffs <service>/prisma/migrations → schema.prisma using a freshly created, empty shadow
 * database on the TEST instance (Prisma requires the shadow database to exist).
 */
function diffAgainstShadow(svc, extraArgs) {
  const test = loadTargets().test;
  requireRunning(test);
  if (test.port === loadTargets().dev.port)
    fail('test and dev targets share a port — refusing to create shadow databases');
  const shadowDb = `shadow_${svc}`;
  runSql(test, `DROP DATABASE IF EXISTS ${shadowDb} WITH (FORCE)`, { database: 'postgres' });
  runSql(test, `CREATE DATABASE ${shadowDb}`, { database: 'postgres' });
  try {
    const res = runPrisma(
      svc,
      [
        'migrate',
        'diff',
        '--from-migrations',
        'prisma/migrations',
        '--to-schema',
        'prisma/schema.prisma',
        ...extraArgs,
      ],
      {
        capture: true,
        allowFailure: true,
        env: {
          // Prisma 7.10 silently no-ops `migrate diff` without a datasource URL; any URL works here.
          MIGRATION_DATABASE_URL: connectionUrl({
            user: 'offline',
            password: 'offline',
            host: '127.0.0.1',
            port: 1,
            database: 'offline',
            schema: svc,
          }),
          SHADOW_DATABASE_URL: connectionUrl({
            user: test.adminUser,
            password: test.adminPassword,
            host: test.host,
            port: test.port,
            database: shadowDb,
            schema: svc,
          }),
        },
      },
    );
    if (res.status === 1) fail(`${svc}: prisma migrate diff failed:\n${res.stderr}${res.stdout}`);
    res.stdout = res.stdout.replace(/^Loaded Prisma config.*\n+/m, '');
    return res;
  } finally {
    runSql(test, `DROP DATABASE IF EXISTS ${shadowDb} WITH (FORCE)`, { database: 'postgres' });
  }
}

/**
 * Prisma does NOT make a migration atomic on PostgreSQL: if statement N fails, statements 1..N-1 stay
 * applied and every later deploy is blocked (P3009). An explicit transaction makes a failure roll back
 * completely (verified). Statements that cannot run in a transaction block must live alone in their own
 * migration, so those files are left unwrapped.
 */
function wrapInTransaction(sql) {
  if (/\bCONCURRENTLY\b/i.test(sql)) {
    console.log(
      '⚠ contains CONCURRENTLY: not wrapped in a transaction — keep it as the ONLY statement in this migration',
    );
    return sql;
  }
  return [
    '-- Generated by `make db-migration` from schema.prisma. Review before applying.',
    '-- Explicit transaction: Prisma does not make migrations atomic on PostgreSQL.',
    '-- Hand-written SQL (RLS policies, CHECK constraints, functions) goes ABOVE the final COMMIT.',
    'BEGIN;',
    '',
    sql.trimEnd(),
    '',
    'COMMIT;',
    '',
  ].join('\n');
}

/**
 * Prisma emits `CREATE SCHEMA IF NOT EXISTS`, which PostgreSQL rejects for roles without
 * database-level CREATE even when the schema already exists. Migrators deliberately lack that
 * privilege, so the statement is replaced by a guarded no-op (the schema is pre-created and
 * owned by the migrator; the guard still creates it inside throwaway shadow databases).
 */
function guardSchemaCreation(svc, sql) {
  return sql.replace(
    `CREATE SCHEMA IF NOT EXISTS "${svc}";`,
    `-- Pre-created by infrastructure bootstrap and owned by sc_${svc}_migrator, which deliberately\n` +
      `-- lacks database-level CREATE. Guarded so the statement is a no-op whenever the schema exists.\n` +
      `DO $$ BEGIN\n  IF to_regnamespace('${svc}') IS NULL THEN CREATE SCHEMA "${svc}"; END IF;\nEND $$;`,
  );
}

if (!commands[command]) {
  const lines = readFileSync(new URL(import.meta.url), 'utf8')
    .split('\n')
    .slice(1);
  console.log(
    lines
      .slice(
        0,
        lines.findIndex((l) => !l.startsWith('//')),
      )
      .join('\n')
      .replace(/^\/\/ ?/gm, ''),
  );
  process.exit(command ? 1 : 0);
}
commands[command]();
